async def seed_plan(session: AsyncSession) -> int:
    """幂等：清空课表后按 PLAN_DAYS 重写；不提交事务，由调用方 commit。返回天数。"""
    await session.execute(delete(PlanDayPart))
    await session.execute(delete(PlanDay))
    days, parts = [], []
    for no, (title, ps) in enumerate(PLAN_DAYS, 1):
        days.append({"day_no": no, "title": title})
        seen = set()
        for subj, part in ps:
            if (subj, part) not in seen:
                seen.add((subj, part))
                parts.append({"day_no": no, "subject": subj, "part": part})
    await session.execute(insert(PlanDay), days)
    await session.execute(insert(PlanDayPart), parts)
    await session.flush()
    return len(days)
